"""python -m eval.generate MODEL OUT: the model's version of each test turn -> OUT/gen/MODEL.json.
Options come from OUT/params.json, written by run.py. The turns are generated by the llama-server at --server-url
(see docs/experiment.md), as many at a time as it has slots, sharing its KV cache."""

import argparse
import json
import sys
import threading
import time
from concurrent.futures import ThreadPoolExecutor, as_completed
from contextlib import contextmanager
from pathlib import Path

import httpx2

from eval.data import test_turns
from eval.model import Model
from eval.progress import tick

ap = argparse.ArgumentParser()
ap.add_argument("model")
ap.add_argument("out", type=Path)
args = ap.parse_args()
p = json.loads((args.out / "params.json").read_text())

t0 = time.time()
model = Model(args.model, p["n_ctx"], p["keep_system_prompt"], vocab_only=True)
client = httpx2.Client(base_url=p["server_url"], timeout=None)


def connect():
    """(KV cache size, slots) of the server's instance of the model, loading it. Exits unless it runs this very GGUF:
    the prompts, stops and banned tokens here all come from it."""
    try:
        slots = client.get("/slots", params={"model": model.name}).raise_for_status().json()
        served = client.get("/props", params={"model": model.name}).raise_for_status().json()["model_path"]
    except httpx2.HTTPError as e:
        sys.exit(f"llama-server at {p['server_url']} can't serve {model.name} ({e}): start it as in docs/experiment.md")
    if Path(served).resolve() != Path(args.model).resolve():  # a single-model server answers any name with its own model
        sys.exit(f"llama-server serves {served} for {model.name}, not {args.model}: start it with --models-dir as in docs/experiment.md")
    return slots[0]["n_ctx"], len(slots)


n_ctx, n_slots = connect()
room, used = threading.Condition(), 0


@contextmanager
def kv_cache(tokens):
    """Waits until `tokens` more fit in the server's KV cache: overflowing it fails every running turn."""
    global used
    with room:
        room.wait_for(lambda: not used or used + tokens <= n_ctx)
        used += tokens
    try:
        yield
    finally:
        with room:
            used -= tokens
            room.notify_all()


def complete(setting, prompt, n_predict, seed):
    """The server stops at end-of-generation tokens, blank lines and the setting's plain-text end markers."""
    return client.post("/completion", json={
        "model": model.name, "prompt": prompt, "n_predict": n_predict, "seed": seed, "return_tokens": True,
        "samplers": ["top_p", "min_p", "temperature"], "top_p": p["top_p"], "min_p": p["min_p"], "temperature": p["temperature"],
        "logit_bias": [[t, False] for t in model.chat.think_ids + model.chat.leave_ids], "stop": ["\n\n", *text_stops[setting]],
    }).raise_for_status().json()


def generate(setting, prompt, seed):
    """(text, finish): finish is "turn end", "blank line" or "length". End-of-turn markers that are control tokens
    but not end-of-generation, like Mistral's [/INST], don't stop the server: they are cut here by token id."""
    with kv_cache(len(prompt) + p["max_tokens"]):
        tokens, text = [], ""
        while True:
            r = complete(setting, prompt + tokens, p["max_tokens"] - len(tokens), seed)
            tokens, text = tokens + r["tokens"], text + r["content"]
            blank = r["stop_type"] == "word" and r["stopping_word"] == "\n\n"
            if not blank or text.strip() or len(tokens) >= p["max_tokens"]:  # leading blank lines don't end the turn
                break
    if (end := next((k for k, t in enumerate(tokens) if t in end_ids[setting]), None)) is not None:
        return model.llm.detokenize(tokens[:end]).decode(errors="ignore").lstrip(), "turn end"
    return text.lstrip(), "blank line" if blank else "length" if r["stop_type"] == "limit" else "turn end"


end_ids = {s: set(model.end_ids(s)) for s in model.settings}
text_stops = {s: [x for x in dict.fromkeys([model.turn_end(s), *model.chat.stops]) if not model.chat.special_ids(x)]
              for s in model.settings}
turns = test_turns(p["n"])
result = {"model": model.name, "n": p["n"], "max_tokens": p["max_tokens"], "temperature": p["temperature"],
          "top_p": p["top_p"], "min_p": p["min_p"], "server_n_ctx": n_ctx, "server_slots": n_slots, "settings": {}}
total = len(p["settings"]) * len(turns)
pool = ThreadPoolExecutor(n_slots)
try:
    for k, s in enumerate(p["settings"]):
        if s not in model.settings:
            print(f"[{model.name}] {s}: skipped, not supported by its template", flush=True)
            tick((k + 1) * len(turns), total)
            continue
        futures = [pool.submit(generate, s, model.chat.tokenize(model.before(s, t["context"])), idx + 1)
                   for idx, t in enumerate(turns)]
        for i, f in enumerate(as_completed(futures)):
            f.result()
            tick(k * len(turns) + i + 1, total)
        result["settings"][s] = [{"idx": idx, "text": text, "finish": finish, "tokens": len(model.chat.tokenize(text))}
                              for idx, (text, finish) in enumerate(f.result() for f in futures)]
        print(f"[{model.name}] {s}: {time.time() - t0:.0f}s", flush=True)
finally:
    pool.shutdown(cancel_futures=True)
result["secs"] = round(time.time() - t0)
(args.out / "gen").mkdir(parents=True, exist_ok=True)
(args.out / "gen" / f"{model.name}.json").write_text(json.dumps(result, ensure_ascii=False, indent=1))
